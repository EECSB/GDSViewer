    ///
    ///Text as squares: the classic five-by-seven pixel font, for writing words into a layout as geometry.
    ///
    ///**Pixels rather than outlines, because that is what lettering on a chip is.** A mask is drawn on a grid,
    ///a curve on one is a staircase anyway, and the text that goes onto silicon - a part number, a name, a
    ///revision - is written in blocks so that every edge lands on the grid and every stroke is one pixel wide,
    ///which is the width a design rule can be checked against. This is the same answer KLayout's TEXT generator
    ///gives, in the font every character display has used since the first ones.
    ///
