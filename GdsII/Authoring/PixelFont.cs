        ///
        ///A line of text as a bitmap, seven rows tall: each character five columns and a column of space between.
        ///
        ///Indexed [row, column], row 0 at the top - the way a picture is read, and the way <see cref="Raster"/>
        ///takes one. No space after the last character, so the bitmap is exactly as wide as the writing.
        ///
        public static bool[,] Bitmap(string text)
        {
            if (string.IsNullOrEmpty(text))
                return new bool[Height, 0];

            var lit = new bool[Height, (text.Length * Advance) - 1];

            for (int i = 0; i < text.Length; i++)
            {
                int glyph = GlyphIndex(text[i]);

                for (int column = 0; column < Width; column++)
                {
                    byte bits = Glyphs[(glyph * Width) + column];

                    for (int row = 0; row < Height; row++)
                    {
                        if (((bits >> row) & 1) == 1)
                            lit[row, (i * Advance) + column] = true;
                    }
                }
            }

            return lit;
        }

        ///<summary>The rows of space between one line of writing and the next: the leading a character display leaves.</summary>
        public const int LineGap = 2;

        ///
        ///Lines of text as one bitmap: each as <see cref="Bitmap"/> draws it, under the one before with
        ///<see cref="LineGap"/> rows between, all from the same left edge - so writing pasted with its line breaks
        ///keeps them. As wide as the longest line, and an empty line is a line's height of nothing.
        ///
        public static bool[,] Lines(IReadOnlyList<string> lines)
        {
            if (lines.Count == 0)
                return new bool[Height, 0];

            var each = new List<bool[,]>(lines.Count);
            int columns = 0;

            foreach (string line in lines)
            {
                var one = Bitmap(line);

                each.Add(one);
                columns = Math.Max(columns, one.GetLength(1));
            }

            var lit = new bool[(lines.Count * Height) + ((lines.Count - 1) * LineGap), columns];

            for (int line = 0; line < each.Count; line++)
            {
                int top = line * (Height + LineGap);

                for (int row = 0; row < Height; row++)
                {
                    for (int column = 0; column < each[line].GetLength(1); column++)
                        lit[top + row, column] = each[line][row, column];
                }
            }

            return lit;
        }

        ///<summary>Which glyph a character is drawn with: its own in the printable range, the question mark otherwise.</summary>
        private static int GlyphIndex(char character)
        {
            if (character < First || character > Last)
                character = '?';

            return character - First;
        }
